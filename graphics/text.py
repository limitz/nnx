def palette_to_rgb(x, palette=DEFAULT_PALETTE):
    if isinstance(x,_np.ndarray):
        x = _torch.from_numpy(x)
    if x.dim() == 2: x = x[None]
    x = _F.one_hot(x, len(palette)).float().squeeze(-4)
    x = x @ palette.to(x.device) #colors(x.device)
    x = x.transpose(-1,-3)
    x = x.transpose(-1,-2)
    return x

    
